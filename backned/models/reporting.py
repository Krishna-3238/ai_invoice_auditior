"""
Reporting Models
================
Pydantic schemas for the final audit reports generated by the
Reporting Agent / Insight Reporter Tool.
"""

from pydantic import BaseModel, Field
from typing import Any, Dict, List, Literal, Optional


class InvoiceReport(BaseModel):
    """Complete audit report for a single invoice — aggregates results
    from every pipeline stage (extraction → translation → data
    validation → business validation)."""

    #  Identity 
    email_id: str = Field(..., description="Email ID")
    filename: str = Field(..., description="Source filename")
    file_path: str = Field(..., description="Absolute file path")

    #  Invoice header (translated) 
    invoice_no: Optional[str] = None
    invoice_date: Optional[str] = None
    po_number: Optional[str] = None
    vendor_id: Optional[str] = None
    vendor_name: Optional[str] = None
    currency: Optional[str] = None
    subtotal: Optional[float] = None
    tax_amount: Optional[float] = None
    total_amount: Optional[float] = None

    #  Translation info 
    source_language: Optional[str] = None
    was_translated: bool = False
    translation_confidence: float = Field(default=1.0, ge=0.0, le=1.0)


    #  Data Validation summary 
    data_validation_status: Optional[str] = None
    data_validation_errors: int = 0
    data_validation_warnings: int = 0
    data_validation_issues: List[Dict[str, Any]] = Field(
        default_factory=list,
    )

    #  Business Validation summary 
    business_validation_status: Optional[str] = None
    business_validation_errors: int = 0
    business_validation_warnings: int = 0
    business_validation_matched: int = 0
    erp_po_found: bool = False
    erp_vendor_found: bool = False
    business_discrepancies: List[Dict[str, Any]] = Field(
        default_factory=list,
    )

    #  Line items (translated) 
    line_items: List[Dict[str, Any]] = Field(default_factory=list)

    #  Final recommendation 
    recommendation: Literal[
        "auto_approve", "manual_review", "reject"
    ] = Field(
        default="manual_review",
        description="Final recommendation for this invoice",
    )
    recommendation_reasons: List[str] = Field(
        default_factory=list,
        description="Reasons supporting the recommendation",
    )

    #  Report file 
    report_html_path: Optional[str] = Field(
        None, description="Path to the generated HTML report file"
    )
    report_json_path: Optional[str] = None


class ReportingSummary(BaseModel):
    """Summary across all invoices processed in a pipeline run."""
    total_invoices: int = 0
    auto_approved: int = 0
    manual_review: int = 0
    rejected: int = 0
    reports: List[InvoiceReport] = Field(default_factory=list)
    output_dir: str = ""
